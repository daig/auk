//! zsh integration (§5.3, D13), injected through `ZDOTDIR`.
//!
//! A pane's zsh starts with `ZDOTDIR` pointing at a daemon-owned directory whose `.zshenv`
//! restores the user's own `ZDOTDIR` (passed as `AUK_USER_ZDOTDIR`, or unset to mean `$HOME`),
//! sources the user's `.zshenv`, and, in interactive shells, loads the hooks. zsh then reads the
//! user's `.zprofile`, `.zshrc` and `.zlogin` from their own directory as usual. Nested shells
//! see the user's `ZDOTDIR` and get no integration.
//!
//! The hooks emit:
//! - `OSC 133 ; D ; <status>` when a command finishes, then `OSC 7` (cwd), `OSC 2` (title) and
//!   `OSC 133 ; A` before each prompt; `OSC 133 ; B` ends the prompt (kept at the end of `PS1`);
//! - `OSC 2` with the command line and `OSC 133 ; C ; cmdline_url=<alias-expanded line>` with
//!   `;typed_url=<typed line>` when a command starts.

use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// The environment variable carrying the user's own `ZDOTDIR` into the shell.
pub const USER_ZDOTDIR_ENV: &str = "AUK_USER_ZDOTDIR";

const ZSHENV: &str = r#"# Auk shell integration (generated by the Auk daemon; rewritten at every start).
# ZDOTDIR points here only so that zsh reads this file first. Restore the user's ZDOTDIR,
# source their .zshenv, then load the hooks in interactive shells.
'builtin' 'typeset' _auk_dir=${${(%):-%x}:A:h}
if [[ -n ${AUK_USER_ZDOTDIR+x} ]]; then
  'builtin' 'export' ZDOTDIR=$AUK_USER_ZDOTDIR
  'builtin' 'unset' AUK_USER_ZDOTDIR
else
  'builtin' 'unset' ZDOTDIR
fi
{
  'builtin' 'typeset' _auk_file=${ZDOTDIR-$HOME}/.zshenv
  [[ ! -r $_auk_file ]] || 'builtin' 'source' '--' $_auk_file
} always {
  if [[ -o interactive ]]; then
    'builtin' 'source' '--' $_auk_dir/auk-integration.zsh
  fi
  'builtin' 'unset' _auk_file _auk_dir
}
"#;

const INTEGRATION: &str = r#"# Auk shell integration hooks: OSC 133 marks, OSC 7 cwd and titles (spec §5.3).
[[ -n ${_auk_loaded-} ]] && return
typeset -g _auk_loaded=1
typeset -gi _auk_running=0
typeset -g _auk_b=$'%{\e]133;B\a%}'

# Percent-encodes $1 into $REPLY, keeping unreserved characters and '/'.
_auk_urlencode() {
  builtin emulate -L zsh
  builtin local LC_ALL=C str=$1 out= c
  builtin local -i i
  for (( i = 1; i <= ${#str}; i++ )); do
    c=${str[i]}
    if [[ $c == [A-Za-z0-9/._~-] ]]; then
      out+=$c
    else
      builtin printf -v c '%%%02X' "'$c"
      out+=$c
    fi
  done
  REPLY=$out
}

_auk_precmd() {
  builtin local -i st=$?
  if (( _auk_running )); then
    builtin print -rn -- $'\e]133;D;'$st$'\a'
    _auk_running=0
  fi
  builtin local REPLY
  _auk_urlencode "$PWD"
  builtin print -rn -- $'\e]7;file://'"$HOST$REPLY"$'\a'
  builtin print -Pn -- '\e]2;%~\a'
  builtin print -rn -- $'\e]133;A\a'
  PS1=${PS1%$_auk_b}$_auk_b
  # Run after hooks that rebuild PS1 (themes add theirs later than this file loads).
  if [[ ${precmd_functions[-1]} != _auk_precmd ]]; then
    precmd_functions=(${precmd_functions:#_auk_precmd} _auk_precmd)
  fi
}

_auk_preexec() {
  _auk_running=1
  builtin local REPLY expanded
  _auk_urlencode "${3:-$1}"
  expanded=$REPLY
  _auk_urlencode "$1"
  builtin print -rn -- $'\e]2;'"${1//[[:cntrl:]]/ }"$'\a'
  builtin print -rn -- $'\e]133;C;cmdline_url='"$expanded;typed_url=$REPLY"$'\a'
}

builtin autoload -Uz add-zsh-hook
add-zsh-hook precmd _auk_precmd
add-zsh-hook preexec _auk_preexec
"#;

/// Writes the integration into `dir` (replacing what an older daemon wrote) and returns the
/// directory to use as the shell's `ZDOTDIR`.
pub fn install(dir: &Path) -> io::Result<PathBuf> {
    fs::create_dir_all(dir)?;
    fs::write(dir.join(".zshenv"), ZSHENV)?;
    fs::write(dir.join("auk-integration.zsh"), INTEGRATION)?;
    Ok(dir.to_owned())
}

/// Whether `shell` is zsh, by its file name.
pub fn is_zsh(shell: &Path) -> bool {
    shell
        .file_name()
        .is_some_and(|n| n == "zsh" || n.to_string_lossy().starts_with("zsh-"))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::process::Command;

    fn temp(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("auk-zsh-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn sources_the_users_files_and_loads_hooks() {
        let root = temp("files");
        let ours = install(&root.join("ours")).unwrap();
        let user = root.join("user");
        fs::create_dir_all(&user).unwrap();
        fs::write(user.join(".zshenv"), "export FROM_ZSHENV=1\n").unwrap();
        fs::write(user.join(".zshrc"), "FROM_ZSHRC=1\n").unwrap();
        let out = Command::new("/bin/zsh")
            .args(["-l", "-i", "-c", "print -r -- $FROM_ZSHENV:$FROM_ZSHRC:$ZDOTDIR:${+functions[_auk_precmd]}:${precmd_functions[(I)_auk_precmd]}"])
            .env("ZDOTDIR", &ours)
            .env(USER_ZDOTDIR_ENV, &user)
            .env("HOME", &root)
            .output()
            .unwrap();
        let text = String::from_utf8_lossy(&out.stdout);
        let line = text.lines().last().unwrap_or_default();
        assert_eq!(line, format!("1:1:{}:1:1", user.display()), "{text}");
        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn non_interactive_shells_get_no_hooks() {
        let root = temp("nonint");
        let ours = install(&root.join("ours")).unwrap();
        let out = Command::new("/bin/zsh")
            .args([
                "-c",
                "print -r -- ${+functions[_auk_precmd]}:${ZDOTDIR-unset}",
            ])
            .env("ZDOTDIR", &ours)
            .env_remove(USER_ZDOTDIR_ENV)
            .env("HOME", &root)
            .output()
            .unwrap();
        assert_eq!(String::from_utf8_lossy(&out.stdout).trim(), "0:unset");
        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn urlencodes_bytes() {
        let root = temp("url");
        let ours = install(&root.join("ours")).unwrap();
        let script = format!(
            "source {}/auk-integration.zsh; _auk_urlencode $'a b/\u{fc}%;\\e'; print -r -- $REPLY",
            ours.display()
        );
        let out = Command::new("/bin/zsh")
            .args(["-f", "-c", &script])
            .output()
            .unwrap();
        assert_eq!(
            String::from_utf8_lossy(&out.stdout).trim(),
            "a%20b/%C3%BC%25%3B%1B"
        );
        let _ = fs::remove_dir_all(&root);
    }

    #[test]
    fn recognizes_zsh() {
        assert!(is_zsh(Path::new("/bin/zsh")));
        assert!(is_zsh(Path::new("/opt/homebrew/bin/zsh-5.9")));
        assert!(!is_zsh(Path::new("/bin/bash")));
    }
}

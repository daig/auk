/// Resolves a manifest icon name: text up to the last `.` is dropped, then an icon name, then an
/// alias; anything else (or nothing) is [`DEFAULT`].
pub fn resolve(name: Option<&str>) -> &'static str {
    let Some(name) = name else { return DEFAULT };
    let name = name.rsplit('.').next().unwrap_or(name);
    if let Ok(i) = NAMES.binary_search(&name) {
        return NAMES[i];
    }
    ALIASES
        .iter()
        .find(|(alias, _)| *alias == name)
        .map_or(DEFAULT, |(_, icon)| icon)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_are_sorted_and_aliases_resolve_to_names() {
        // Tern's docs say 207 but its table lists 208 names; the table wins.
        assert_eq!(NAMES.len(), 208);
        assert!(NAMES.windows(2).all(|w| w[0] < w[1]));
        for (alias, icon) in ALIASES {
            assert!(NAMES.binary_search(icon).is_ok(), "{alias} -> {icon}");
        }
    }

    #[test]
    fn resolution() {
        assert_eq!(resolve(None), "puzzle");
        assert_eq!(resolve(Some("box")), "box");
        assert_eq!(resolve(Some("icon.folder")), "folder");
        assert_eq!(resolve(Some("success")), "check");
        assert_eq!(resolve(Some("nope")), "puzzle");
        assert_eq!(resolve(Some("")), "puzzle");
    }
}
